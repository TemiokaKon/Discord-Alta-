// Helper function to get an icon
function getIcon(category, name, className = '') {
    if (Icons[category] && Icons[category][name]) {
        const svg = Icons[category][name];
        return className ? svg.replace('<svg', `<svg class="${className}"`) : svg;
    }
    return '';
}

// Helper function to create an icon element
function createIconElement(category, name, className = '') {
    const div = document.createElement('div');
    div.innerHTML = getIcon(category, name, className);
    return div.firstChild;
}

